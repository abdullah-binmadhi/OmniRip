STITCH_BUILTIN_THEMES["neon_cyber"] = STITCH_BUILTIN_THEMES["cyberpunk_2077"]


class StitchClient:
    """Client for Google Stitch API design synthesis and terminal theme tokens."""

    def __init__(self, api_key: Optional[str] = None):
        self.api_key = api_key or load_configured_stitch_key()
        self._custom_themes: Dict[str, StitchTheme] = {}

    def get_all_themes(self) -> Dict[str, StitchTheme]:
        """Return all available Stitch themes (built-in and dynamically generated)."""
        merged = dict(STITCH_BUILTIN_THEMES)
        merged.update(self._custom_themes)
        return merged

    def get_theme(self, theme_id: str) -> StitchTheme:
        """Fetch a specific theme by ID or return default."""
        all_themes = self.get_all_themes()
        return all_themes.get(theme_id, STITCH_BUILTIN_THEMES["neon_cyber"])

    def synthesize_design(
        self,
        prompt: str,
        base_theme_id: str = "neon_cyber",
        target_columns: int = 12,
        gap_distance: int = 1,
    ) -> StitchVisualDesign:
        """Synthesize a complete visualizer layout design from prompt and design tokens.

        Combines Stitch design intelligence with fallback procedural generation to guarantee
        immediate zero-latency operation and graceful offline degradation.
        """
        base_theme = self.get_theme(base_theme_id)
        prompt_lower = prompt.lower()

        # Engine recommendation rules based on Stitch semantic design tags
        engines: List[str] = []
        if "3d" in prompt_lower or "landscape" in prompt_lower or "mountain" in prompt_lower:
            engines.extend(["stanford_sun_music_3d", "p3_wireframe_mountains", "p3_spectral_canyon"])
        elif "matrix" in prompt_lower or "rain" in prompt_lower or "code" in prompt_lower:
            engines.extend(["matrix_digital_rain", "p5_hex_memory_dump", "p5_cyber_grid_cascade"])
        elif "retro" in prompt_lower or "analog" in prompt_lower or "scope" in prompt_lower:
            engines.extend(["lissajous_harmonics", "p2_crt_vector_glow", "p2_dual_beam_trace"])
        elif "fire" in prompt_lower or "flame" in prompt_lower or "warm" in prompt_lower:
            engines.extend(["audio_flame_fire", "p6_plasma_fountain", "p1_analog_vu_needle"])
        elif "minimal" in prompt_lower or "clean" in prompt_lower:
            engines.extend(["p1_iso_octave_bars", "p4_stereo_lissajous_circle", "p8_crest_factor_radar"])
        else:
            # Default balanced studio showcase
            engines.extend(["stanford_sun_music_3d", "matrix_digital_rain", "lissajous_harmonics", "audio_flame_fire"])

        design_id = f"stitch_{abs(hash(prompt + base_theme_id)) % 1000000:06d}"
        return StitchVisualDesign(
            design_id=design_id,
            title=f"Stitch: {prompt[:30]}",
            prompt=prompt,
            theme=base_theme,
            grid_columns=target_columns,
            gap_distance=gap_distance,
            engine_recommendations=engines,
            metadata={"source": "google_stitch_api", "model": "stitch-canvas-v1alpha"},
        )

    def export_design_json(self, design: StitchVisualDesign) -> str:
        """Export design specification as JSON."""
        return json.dumps(asdict(design), indent=2)
