STITCH_API_ENDPOINT = "https://stitch.googleapis.com/v1alpha"


def load_configured_stitch_key() -> str:
    """Load Stitch API key from environment variable or user config file."""
    env_key = os.environ.get("GOOGLE_STITCH_API_KEY") or os.environ.get("STITCH_API_KEY")
    if env_key:
        return env_key.strip()
    if STITCH_KEY_FILE.is_file():
        try:
            return STITCH_KEY_FILE.read_text(encoding="utf-8").strip()
        except Exception:
            pass
    return ""


@dataclass
class StitchTheme:
    """A Stitch design theme with styling tokens for the terminal visualizer canvas."""

    theme_id: str
    name: str
    description: str
    primary_color: str
    secondary_color: str
    accent_color: str
    background_color: str
    surface_color: str
    text_color: str
    gradient_stops: List[str] = field(default_factory=list)
    border_style: str = "heavy"
    ascii_art_style: str = "block"

    def to_css_dict(self) -> Dict[str, str]:
        """Convert theme tokens to Textual CSS color mappings."""
        return {
            "primary": self.primary_color,
            "secondary": self.secondary_color,
            "accent": self.accent_color,
            "background": self.background_color,
            "surface": self.surface_color,
            "text": self.text_color,
        }


@dataclass
class StitchVisualDesign:
    """Design specification generated by Stitch for visualizer canvas layouts."""

    design_id: str
    title: str
    prompt: str
    theme: StitchTheme
    grid_columns: int = 12
    gap_distance: int = 1
    engine_recommendations: List[str] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)


